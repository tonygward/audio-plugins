import test from 'node:test';
import assert from 'node:assert/strict';
import {nextBetaVersion,betaChangelog,shouldBump,pullRequestBuilding,pullRequestBuilt,QUIET_RELEASE_NOTE} from '../scripts/release/bump-beta.mjs';
test('increments only beta patch',()=>{
  assert.equal(nextBetaVersion('1.3.0\n'),'1.3.1');
  assert.equal(nextBetaVersion('1.3.9'),'1.3.10');
  assert.throws(()=>nextBetaVersion('1.3.0-rc'));
});
test('never increments an autogenerated beta version commit',()=>{
  assert.equal(shouldBump({message:'[beta-version] 1.3.1'}),false);
  assert.equal(shouldBump({message:'Implement EQ feature'}),true);
});
test('a source merge while the current version is still unreleased bumps too, folding that version in',()=>{
  const sha='a'.repeat(40);
  // 0.5.15 was being packaged when this merge landed: its notes and the merge's notes ship together in 0.5.16.
  const pending='# T\n\n## Unreleased\n\n- New tooltip.\n\n## 0.5.15\n\n- Earlier change.\n\n## 0.5.14\n\n- Old\n';
  const result=betaChangelog(pending,'0.5.16',sha,'0.5.15');
  assert.match(result,/## 0\.5\.16\n\n- New tooltip\.\n\n- Earlier change\.\n\n## 0\.5\.14\n\n- Old\n/);
  assert.ok(!/## 0\.5\.15/.test(result)&&!result.includes('Unreleased'),'the unreleased version and Unreleased are gone');
  // A quiet unreleased version adds nothing; with no new notes either, the new version stays quiet.
  const quiet=`# T\n\n## Unreleased\n\n- New tooltip.\n\n## 0.5.15\n\n${QUIET_RELEASE_NOTE}\n\n## 0.5.14\n\n- Old\n`;
  assert.match(betaChangelog(quiet,'0.5.16',sha,'0.5.15'),/## 0\.5\.16\n\n- New tooltip\.\n\n## 0\.5\.14/);
  assert.match(betaChangelog(`# T\n\n## 0.5.15\n\n${QUIET_RELEASE_NOTE}\n\n## 0.5.14\n\n- Old\n`,'0.5.16',sha,'0.5.15'),/## 0\.5\.16\n\nBehind-the-scenes[^\n]*\n\n## 0\.5\.14/);
  // A released version is never folded.
  assert.match(betaChangelog(pending,'0.5.16',sha),/## 0\.5\.16\n\n- New tooltip\.\n\n## 0\.5\.15\n\n- Earlier change\./);
  assert.throws(()=>betaChangelog(pending,'0.5.16',sha,'0.5'),/Invalid unreleased version/);
});
test('new notes prepend one matching section and retain existing changelog',()=>{
  const old='# Songsmith Plugins\n\n## 1.3.0\n\n- Old\n';
  const result=betaChangelog(old,'1.3.1','a'.repeat(40));
  assert.match(result,/## 1\.3\.1\n/);
  assert.ok(result.includes(old.slice(old.indexOf('## 1.3.0'))));
  assert.throws(()=>betaChangelog(result,'1.3.1','a'.repeat(40)));
});
test('notes are plain feature text with no hashes or pull request titles',()=>{
  const sha='a'.repeat(40);
  const old='# T\n\n## Unreleased\n\n- **Meter:** new thing.\n\n## 1.3.0\n\n- Old\n';
  const result=betaChangelog(old,'1.3.1',sha);
  assert.match(result,/## 1\.3\.1\n\n- \*\*Meter:\*\* new thing\.\n\n## 1\.3\.0/);
  assert.ok(!result.includes('Unreleased')&&!result.includes(sha.slice(0,12))&&!/pull request/i.test(result));
  assert.match(betaChangelog('# T\n\n## 1.3.0\n\n- Old\n','1.3.1',sha),/## 1\.3\.1\n\nBehind-the-scenes improvements/);
  assert.match(betaChangelog('# T\n\n## Unreleased\n\n## 1.3.0\n\n- Old\n','1.3.1',sha),/Behind-the-scenes/);
});

// ---- Two builds per release: the pull request build vouches for the bump ----
const repo='tonygward/audio-plugins',head='b'.repeat(40);
const mergedPr={merged_at:'2026-11-12T01:00:00Z',base:{ref:'main'},head:{sha:head}};
const goodRun={head_sha:head,event:'pull_request',status:'completed',conclusion:'success',path:'.github/workflows/build.yml@refs/pull/9/merge',repository:{full_name:repo},head_repository:{full_name:repo}};
test('a bump needs a successful pull request Build at the exact head that merged',()=>{
  assert.equal(pullRequestBuilt({prs:[mergedPr],runs:[goodRun]}),true);
  assert.equal(pullRequestBuilt({prs:[mergedPr],runs:[{...goodRun,conclusion:'failure'}]}),false,'a failed build');
  assert.equal(pullRequestBuilt({prs:[mergedPr],runs:[{...goodRun,head_sha:'c'.repeat(40)}]}),false,'a build of a different head');
  assert.equal(pullRequestBuilt({prs:[mergedPr],runs:[{...goodRun,event:'push'}]}),false,'not a pull request build');
  assert.equal(pullRequestBuilt({prs:[mergedPr],runs:[{...goodRun,path:'.github/workflows/other.yml@main'}]}),false,'a different workflow');
  assert.equal(pullRequestBuilt({prs:[mergedPr],runs:[{...goodRun,head_repository:{full_name:'someone/else'}}]}),false,'a fork');
  assert.equal(pullRequestBuilt({prs:[mergedPr],runs:[{...goodRun,status:'in_progress',conclusion:null}]}),false,'not finished');
});
test('no merged pull request, an unmerged one or a base other than main never vouches',()=>{
  assert.equal(pullRequestBuilt({prs:[],runs:[goodRun]}),false);
  assert.equal(pullRequestBuilt({prs:[{...mergedPr,merged_at:null}],runs:[goodRun]}),false);
  assert.equal(pullRequestBuilt({prs:[{...mergedPr,base:{ref:'dev'}}],runs:[goodRun]}),false);
  assert.equal(pullRequestBuilt({prs:null,runs:[goodRun]}),false);
});
test('a pull request build still queued or running is waited for, a finished one is not',()=>{
  const running={...goodRun,status:'in_progress',conclusion:null};
  assert.equal(pullRequestBuilding({prs:[mergedPr],runs:[running]}),true);
  assert.equal(pullRequestBuilding({prs:[mergedPr],runs:[{...running,status:'queued'}]}),true);
  assert.equal(pullRequestBuilding({prs:[mergedPr],runs:[goodRun]}),false);
  assert.equal(pullRequestBuilding({prs:[mergedPr],runs:[{...running,head_sha:'c'.repeat(40)}]}),false,'another head');
  assert.equal(pullRequestBuilding({prs:[mergedPr],runs:[{...running,event:'push'}]}),false);
  assert.equal(pullRequestBuilding({prs:[],runs:[running]}),false);
});
