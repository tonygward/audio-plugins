import test from 'node:test';
import assert from 'node:assert/strict';
import {nextBetaVersion,betaChangelog,shouldBump} from '../scripts/release/bump-beta.mjs';
test('increments only beta patch',()=>{
  assert.equal(nextBetaVersion('1.3.0\n'),'1.3.1');
  assert.equal(nextBetaVersion('1.3.9'),'1.3.10');
  assert.throws(()=>nextBetaVersion('1.3.0-rc'));
});
test('never increments an autogenerated beta version commit',()=>{
  assert.equal(shouldBump({message:'[beta-version] 1.3.1',tagFound:true}),false);
  assert.equal(shouldBump({message:'Implement EQ feature',tagFound:true}),true);
  assert.equal(shouldBump({message:'Implement EQ feature',tagFound:false}),false);
});
test('new notes prepend one matching section and retain existing changelog',()=>{
  const old='# Songsmith Plugins\n\n## 1.3.0\n\n- Old\n';
  const result=betaChangelog(old,'1.3.1','a'.repeat(40),'Fix band hover\nBody');
  assert.match(result,/## 1\.3\.1\n/);
  assert.match(result,/- Fix band hover/);
  assert.ok(result.includes(old.slice(old.indexOf('## 1.3.0'))));
  assert.throws(()=>betaChangelog(result,'1.3.1','a'.repeat(40),'duplicate'));
});
