import test from 'node:test';
import assert from 'node:assert/strict';
import { assessIssue, promptFromIssue, promptPath, resolveFromIssues, needsDetailMarker } from '../issue-prompt.mjs';

const GOOD = `## Objective and user value\nLet musicians pick a two to one ratio so gentle compression is possible.\n\n## Implementation\nAdd the ratio to FETParams.h and FETEngine.h; keep the existing ratio indexes stable.\n\n## Acceptance criteria and tests\nThe new ratio appears last in the list. Add a unit test that older sessions load unchanged.\n`;
const THIN = '## Objective\nMake the compressor nicer for everybody please.';
const card = (taskId, extra = {}) => ({ itemId: 'item-' + taskId, status: 'Doing', issue: 5, state: 'OPEN', repository: 'o/r', taskId, title: `${taskId} — Add two to one ratio`, execution: null, ...extra });

test('an issue with an objective, scope, acceptance criteria and tests is enough; a combined heading covers both acceptance and tests', () => {
  assert.deepEqual(assessIssue(GOOD), { ok: true, deferred: false, missing: [] });
});

test('each missing part is named, and thin sections do not count', () => {
  const r = assessIssue('## Objective\nMake the thing better for everyone who uses it today.\n\n## Implementation\nx\n');
  assert.equal(r.ok, false);
  assert.equal(r.missing.length, 3);
  assert.ok(r.missing.some(m => /^scope or implementation/.test(m)) && r.missing.some(m => /^acceptance criteria/.test(m)) && r.missing.some(m => /^tests/.test(m)));
  assert.equal(assessIssue('Just do it please.').missing.length, 4);
});

test('an issue that says it is deferred is left alone, not blocked', () => {
  assert.deepEqual(assessIssue(`**Execution:** Deferred; do not start.\n\n${GOOD}`), { ok: false, deferred: true, missing: [] });
});

test('the prompt path follows the ID prefix, and the generated prompt is valid, ready and links the issue', () => {
  assert.equal(promptPath('ACOMP-12', 'ACOMP-12 — Add two to one ratio'), 'analog-compressor/prompts/12-add-two-to-one-ratio.md');
  assert.equal(promptPath('EQ-42', 'EQ-42: Fix it!'), 'eq/prompts/42-fix-it.md');
  assert.equal(promptPath('AUTO-14', 'AUTO-14 — Record why'), 'shared/prompts/AUTO-14-record-why.md');
  const p = promptFromIssue(card('ACOMP-12'), GOOD, { issueUrl: 'https://github.com/o/r/issues/5' });
  assert.equal(p.id, 'ACOMP-12'); assert.equal(p.file, 'analog-compressor/prompts/12-add-two-to-one-ratio.md');
  assert.equal(p.deferred, false); assert.equal(p.blocked, false); assert.doesNotMatch(p.generated.text, /^(status|execution):/m); assert.equal(p.model, 'sonnet');
  assert.ok(p.generated.text.includes('**Tracking issue:** https://github.com/o/r/issues/5')); assert.match(p.generated.text, /Generated by Matrix/);
  assert.ok(p.generated.text.includes('two to one ratio so gentle'));
});

function fakeIo(bodies, { existing = [] } = {}) {
  const log = { comments: [], moves: [] };
  return { log, io: {
    issueBody: async (r, n) => bodies[n] ?? '',
    hasComment: async (r, n, marker) => existing.includes(marker) || log.comments.some(c => c.body.includes(marker)),
    comment: async (r, n, body) => { log.comments.push({ n, body }); },
    moveToBlocked: async id => { log.moves.push(id); } } };
}
const base = (cards, io, extra = {}) => ({ board: { cards }, prompts: [], pulls: [], tasks: {}, io, statuses: ['Doing', 'Todo'], executionRepositories: ['o/r'], dryRun: false, ...extra });

test('enough detail: a prompt is generated and nothing is commented or moved', async () => {
  const { io, log } = fakeIo({ 5: GOOD });
  const r = await resolveFromIssues(base([card('ACOMP-12')], io));
  assert.deepEqual(r.prompts.map(p => p.id), ['ACOMP-12']); assert.deepEqual(r.blocked, []);
  assert.equal(log.comments.length, 0); assert.equal(log.moves.length, 0);
});

test('not enough detail: one comment naming what is missing, and the card moves to Blocked; the same text is not commented twice', async () => {
  const a = card('ACOMP-12'), { io, log } = fakeIo({ 5: THIN });
  const r = await resolveFromIssues(base([a], io));
  assert.deepEqual(r.blocked, ['ACOMP-12']); assert.equal(a.status, 'Blocked'); assert.deepEqual(log.moves, ['item-ACOMP-12']);
  assert.equal(log.comments.length, 1);
  assert.match(log.comments[0].body, /does not have enough detail/); assert.match(log.comments[0].body, /acceptance criteria/); assert.match(log.comments[0].body, /move this card back to Todo or Doing/);
  const marker = log.comments[0].body.split('\n')[0];
  const again = fakeIo({ 5: THIN }, { existing: [marker] });
  await resolveFromIssues(base([card('ACOMP-12')], again.io));
  assert.equal(again.log.comments.length, 0); assert.equal(again.log.moves.length, 1);
});

test('a dry run, deferred or Separate cards, other repositories, existing prompts and existing work are never touched', async () => {
  const { io, log } = fakeIo({ 5: THIN });
  await resolveFromIssues(base([card('ACOMP-12')], io, { dryRun: true }));
  await resolveFromIssues(base([card('ACOMP-13', { execution: 'Separate' }), card('ACOMP-14', { execution: 'Deferred' }), card('ACOMP-15', { repository: 'o/other' }), card('ACOMP-16', { status: 'Todo' }), card('ACOMP-17')], io,
    { statuses: ['Doing'], prompts: [{ id: 'ACOMP-17' }] }));
  await resolveFromIssues(base([card('ACOMP-18'), card('ACOMP-19')], io, { merged: new Set(['ACOMP-18']), open: new Set(['ACOMP-19']) }));
  await resolveFromIssues(base([card('ACOMP-20')], io, { tasks: { 'ACOMP-20': { state: 'interrupted' } } }));
  assert.equal(log.comments.length, 0); assert.equal(log.moves.length, 0);
});

test('the needs-detail marker changes when the missing list or the issue text changes', () => {
  assert.notEqual(needsDetailMarker('A-01', 'aaa'), needsDetailMarker('A-01', 'bbb'));
});

test('a task resumed with committed work regenerates its prompt even though its pull request is open; other open-PR tasks do not', async () => {
  const { io } = fakeIo({ 5: GOOD });
  const open = new Set(['ACOMP-12']);
  const resumed = await resolveFromIssues(base([card('ACOMP-12')], io, { open, tasks: { 'ACOMP-12': { state: 'pending', resumeWork: true } } }));
  assert.deepEqual(resumed.prompts.map(p => p.id), ['ACOMP-12']);
  const notResumed = await resolveFromIssues(base([card('ACOMP-12')], io, { open, tasks: { 'ACOMP-12': { state: 'pending' } } }));
  assert.deepEqual(notResumed.prompts, []);
  const merged = await resolveFromIssues(base([card('ACOMP-12')], io, { merged: new Set(['ACOMP-12']), open, tasks: { 'ACOMP-12': { state: 'pending', resumeWork: true } } }));
  assert.deepEqual(merged.prompts, [], 'merged work is never rebuilt');
});

test('boilerplate such as "not queued or started" is not a deferral', () => {
  assert.equal(assessIssue(`**Status:** Backlog only; not queued or started.\n\n${GOOD}`).deferred, false);
});
